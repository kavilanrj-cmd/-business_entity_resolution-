def _text_len(series: pd.Series) -> np.ndarray:
    s = series.fillna("")
    return s.str.len().to_numpy(dtype="int32")


def _len_stats(parts: list[np.ndarray]) -> dict[str, object]:
    a = np.concatenate(parts) if parts else np.zeros(1, dtype="int32")
    return {
        "min": int(a.min()),
        "p25": int(np.percentile(a, 25)),
        "median": int(np.percentile(a, 50)),
        "mean": round(float(a.mean()), 2),
        "p75": int(np.percentile(a, 75)),
        "p95": int(np.percentile(a, 95)),
        "p99": int(np.percentile(a, 99)),
        "max": int(a.max()),
    }


def describe_dataframe(df: pd.DataFrame, label: str) -> dict[str, object]:
    """Collect shape / dtype / null / duplicate statistics for one in-memory table."""
    stats: dict[str, object] = {
        "label": label,
        "shape": tuple(int(x) for x in df.shape),
        "columns": list(df.columns),
        "dtypes": {c: str(t) for c, t in df.dtypes.items()},
        "null_counts": {c: int(df[c].isna().sum()) for c in df.columns},
        "null_fraction": {
            c: (float(df[c].isna().mean()) if len(df) else 0.0) for c in df.columns
        },
    }
    if ID_COLUMN in df.columns:
        ids = df[ID_COLUMN]
        stats["id_nulls"] = int(ids.isna().sum())
        stats["id_duplicates"] = int(ids.duplicated(keep=False).sum())
        stats["id_unique"] = int(ids.nunique(dropna=True))
    for col in (NAME_COLUMN, ADDRESS_COLUMN, COUNTRY_COLUMN):
        if col in df.columns:
            s = df[col].dropna().astype(str)
            stats[f"{col}_empty_string"] = int((s.str.strip() == "").sum())
            stats[f"{col}_unique"] = int(s.nunique())
            if len(s):
                stats[f"{col}_len_mean"] = round(float(s.str.len().mean()), 2)
                stats[f"{col}_len_median"] = float(s.str.len().median())
    for col in (NAME_COLUMN, ADDRESS_COLUMN):
        if col in df.columns and ID_COLUMN in df.columns:
            stats[f"{col}_duplicate_rows"] = int(df.duplicated(subset=[ID_COLUMN, col], keep=False).sum())
    return stats


def profile_tsv(
    path: str | Path,
    label: str | None = None,
    *,
    chunksize: int = DEFAULT_CHUNK_ROWS,
) -> dict[str, object]:
    """Stream a TSV and return the same statistics as :func:`describe_dataframe`.

    Bounded memory regardless of file size: ids and names are reduced to 64-bit
    hashes for the uniqueness counts, and length statistics are accumulated as
    int32 arrays.  The dataset is never modified.
    """
    path = Path(path)
    name = label or path.name
    cols = _header(path)

    rows = 0
    nulls = {c: 0 for c in cols}
    blank = {c: 0 for c in cols}
    countries: dict[str, int] = {}
    name_len: list[np.ndarray] = []
    addr_len: list[np.ndarray] = []
    id_hash: list[np.ndarray] = []
    name_hash: list[np.ndarray] = []
    id_bad_format = 0
    id_prefix: dict[str, int] = {}

    has_id = ID_COLUMN in cols
    has_name = NAME_COLUMN in cols
    has_addr = ADDRESS_COLUMN in cols
    has_country = COUNTRY_COLUMN in cols

    for chunk in read_tsv_chunks(path, chunksize, usecols=cols):
        rows += len(chunk)
        for c in nulls:
            s = chunk[c]
            nulls[c] += int(s.isna().sum())
            blank[c] += int((s.fillna("").str.strip() == "").sum())
        if has_country:
            for k, v in chunk[COUNTRY_COLUMN].fillna("<NA>").value_counts().to_dict().items():
                countries[str(k)] = countries.get(str(k), 0) + int(v)
        if has_name:
            name_len.append(_text_len(chunk[NAME_COLUMN]))
            name_hash.append(pd.util.hash_pandas_object(
                chunk[NAME_COLUMN].fillna(""), index=False).to_numpy(dtype="uint64"))
        if has_addr:
            addr_len.append(_text_len(chunk[ADDRESS_COLUMN]))
        if has_id:
            ids = chunk[ID_COLUMN].astype(str)
            id_hash.append(pd.util.hash_pandas_object(ids, index=False).to_numpy(dtype="uint64"))
            for pfx, cnt in ids.str.extract(r"^(S[123])-", expand=False).fillna("?").value_counts().items():
                id_prefix[str(pfx)] = id_prefix.get(str(pfx), 0) + int(cnt)
            id_bad_format += int((~ids.str.match(r"^S[123]-\d+$")).sum())

    ih = np.concatenate(id_hash) if id_hash else np.zeros(0, dtype="uint64")
    uniq_id, cnt_id = np.unique(ih, return_counts=True)
    nh = np.concatenate(name_hash) if name_hash else np.zeros(0, dtype="uint64")

    stats: dict[str, object] = {
        "label": name,
        "path": str(path),
        "size_mb": round(path.stat().st_size / 1024**2, 1),
        "header": cols,
        "columns": cols,
        "shape": (rows, len(cols)),
        "n_rows": rows,
        "dtypes": {c: "string (read with dtype=str)" for c in cols},
        "is_record_table": bool(has_id and has_name),
        "null_counts": nulls,
        "null_fraction": {c: (round(v / rows, 6) if rows else 0.0) for c, v in nulls.items()},
        "empty_or_whitespace_only": blank,
    }
    if has_id:
        stats["id_unique"] = int(uniq_id.size)
        stats["id_duplicates"] = int(cnt_id[cnt_id > 1].sum()) if cnt_id.size else 0
        stats["id_prefix_counts"] = id_prefix
        stats["id_bad_format"] = id_bad_format
    if nh.size:
        stats[f"{NAME_COLUMN}_unique"] = int(np.unique(nh).size)
    if name_len:
        stats[f"{NAME_COLUMN}_len"] = _len_stats(name_len)
    if addr_len:
        stats[f"{ADDRESS_COLUMN}_len"] = _len_stats(addr_len)
    if countries:
        stats["n_countries"] = len(countries)
        stats["country_counts"] = dict(sorted(countries.items(), key=lambda kv: -kv[1]))
    return stats
