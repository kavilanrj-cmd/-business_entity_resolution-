#: Default rows per chunk for streaming reads.
DEFAULT_CHUNK_ROWS = 300_000

#: Values treated as missing in the input files.
NA_VALUES: tuple[str, ...] = ("", "NA", "N/A", "null", "NULL", "nan", "NaN")

#: Entity ids in this data set are ``S<source>-<digits>``; derived from the
#: files, not assumed, and only used for diagnostics.
ID_PATTERN = re.compile(r"^(?P<source>S[123])-(?P<number>\d+)$")

