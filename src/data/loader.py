# --------------------------------------------------------------------------
# dataset root resolution
# --------------------------------------------------------------------------
def _has_split(root: Path, split: str) -> bool:
    directory = root / split
    if not directory.is_dir():
        return False
    return all((directory / f"{split}_{source}.tsv").exists() for source in SOURCES)


def resolve_dataset_root(prefer: str | Path | None = None) -> Path:
    """Return the directory that holds the real ``train/`` and ``test/`` data.

    ``prefer`` short-circuits detection and is validated.  Otherwise the
    candidates in :data:`DATASET_ROOTS` are probed in order and the first one
    containing both splits wins, so the real data is preferred over the fixture.
    """
    if prefer is not None:
        candidate = Path(prefer)
        if not _has_split(candidate, "train") and not _has_split(candidate, "test"):
            raise FileNotFoundError(
                f"No train/ or test/ source files under {candidate}. Expected e.g. "
                f"{candidate / 'train' / 'train_source1.tsv'}"
            )
        return candidate
    for root in DATASET_ROOTS:
        if _has_split(root, "train") and _has_split(root, "test"):
            return root
    probed = "\n  ".join(str(r) for r in DATASET_ROOTS)
    raise FileNotFoundError(
        "Could not locate the dataset. Probed:\n  " + probed + "\n"
        "Expected layout:\n"
        "  <root>/train/{train_source1,train_source2,train_source3,train_ground_truth}.tsv\n"
        "  <root>/test/{test_source1,test_source2,test_source3}.tsv"
    )


@lru_cache(maxsize=1)
def dataset_root() -> Path:
    """Auto-detected dataset root (cached)."""
    root = resolve_dataset_root()
    LOGGER.debug("Resolved dataset root: %s", root)
    return root


def default_train_dir() -> str:
    return str(dataset_root() / "train")


def default_test_dir() -> str:
    return str(dataset_root() / "test")


# --------------------------------------------------------------------------
# reading
# --------------------------------------------------------------------------
def _normalise_columns(df: pd.DataFrame) -> pd.DataFrame:
    df = df.rename(columns=lambda c: COLUMN_ALIASES.get(str(c).strip().lower(), str(c).strip()))
    if ID_COLUMN in df.columns:
        df[ID_COLUMN] = df[ID_COLUMN].astype("string").str.strip()
    for col in (NAME_COLUMN, ADDRESS_COLUMN, COUNTRY_COLUMN):
        if col in df.columns:
            df[col] = df[col].astype("string")
    return df


def _read_csv(path: Path, nrows: int | None, usecols, chunksize: int | None):
    kwargs: dict = {
        "sep": "\t",
        "dtype": str,
        "keep_default_na": False,
        "na_values": list(NA_VALUES),
        "encoding": "utf-8",
    }
    if nrows is not None:
        kwargs["nrows"] = nrows
    if usecols is not None:
        kwargs["usecols"] = list(usecols)
    if chunksize is not None:
        kwargs["chunksize"] = chunksize
    return pd.read_csv(path, **kwargs)


def _header(path: Path) -> list[str]:
    with path.open("r", encoding="utf-8") as fh:
        return fh.readline().rstrip("\n").split("\t")


def find_file(directory: str | Path, *patterns: str) -> Path:
    """Locate a file inside ``directory`` by trying a set of name patterns.

    Falls back to a fuzzy search (``*source1*.tsv``) so the loader keeps working
    when the challenge files use slightly different prefixes.
    """
    directory = Path(directory)
    if not directory.is_dir():
        raise FileNotFoundError(f"Directory not found: {directory}")
    for pattern in patterns:
        candidate = directory / pattern
        if candidate.exists():
            return candidate
    for pattern in patterns:
        matches = sorted(directory.glob("*" + pattern))
        if matches:
            return matches[0]
    raise FileNotFoundError(
        f"None of {list(patterns)} found in {directory}. Available: "
        f"{[p.name for p in sorted(directory.glob('*'))]}"
    )


def read_tsv(
    path: str | Path,
    name: str | None = None,
    *,
    nrows: int | None = None,
    usecols: list[str] | None = None,
) -> pd.DataFrame:
    """Read a whole TSV into memory, coercing every column to ``str``.

    Warns when the file is large: the real Source 2/3 tables need several GB
    and should be streamed with :func:`read_tsv_chunks` instead.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f"Required file not found: {path}\n"
            "Expected layout:\n"
            "  <root>/train/{train_source1,train_source2,train_source3,train_ground_truth}.tsv\n"
            "  <root>/test/{test_source1,test_source2,test_source3}.tsv"
        )
    label = name or path.name
    if nrows is None and path.stat().st_size > 200 * 1024**2:
        LOGGER.warning(
            "%s is %.0f MB; reading it whole may exhaust memory. "
            "Prefer read_tsv_chunks()/RawDataset.iter_chunks().",
            label, path.stat().st_size / 1024**2,
        )
    df = _normalise_columns(_read_csv(path, nrows, usecols, None))
    LOGGER.info("Loaded %-28s rows=%-10d cols=%s", label, len(df), list(df.columns))
    return df


def read_tsv_chunks(
    path: str | Path,
    chunksize: int = DEFAULT_CHUNK_ROWS,
    *,
    usecols: list[str] | None = None,
) -> Iterator[pd.DataFrame]:
    """Stream a TSV in fixed-size chunks with bounded memory."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")
    LOGGER.info("Streaming %-24s chunksize=%d cols=%s", path.name, chunksize, usecols or "all")
    for chunk in _read_csv(path, None, usecols, chunksize):
        yield _normalise_columns(chunk)


def source_path(split: str, source: str, root: str | Path | None = None) -> Path:
    """Path of ``<split>_<source>.tsv`` under ``root`` (auto-detected if ``None``)."""
    base = Path(root) if root is not None else dataset_root()
    directory = base if base.name == split else base / split
    return find_file(
        directory,
        f"{split}_{source}.tsv",
        f"{source}.tsv",
        f"{split}{source}.tsv",
    )


@dataclass
class RawDataset:
    """The three record tables for a split, already string-typed."""

    source1: pd.DataFrame
    source2: pd.DataFrame
    source3: pd.DataFrame
    split: str

    def table(self, source: str) -> pd.DataFrame:
        return {SOURCE1: self.source1, SOURCE2: self.source2, SOURCE3: self.source3}[source]

    def __iter__(self):
        for source in SOURCES:
            yield source, self.table(source)

    def iter_chunks(
        self,
        source: str,
        chunksize: int = DEFAULT_CHUNK_ROWS,
        *,
        usecols: list[str] | None = None,
        root: str | Path | None = None,
    ) -> Iterator[pd.DataFrame]:
        """Stream one source table of this split without materialising it."""
        yield from read_tsv_chunks(source_path(self.split, source, root), chunksize, usecols=usecols)

    @property
    def pool(self) -> pd.DataFrame:
        """Source 2 stacked on Source 3 -- the retrieval pool."""
        return pd.concat([self.source2, self.source3], ignore_index=True)


def load_split(root: str | Path | None = None, split: str = "train") -> RawDataset:
    """Load the three record tables for ``split`` into memory.

    ``root`` defaults to the auto-detected dataset root.  For the real data use
    :func:`stream_split` / :meth:`RawDataset.iter_chunks` instead of this.
    """
    tables = {}
    for source in SOURCES:
        path = source_path(split, source, root)
        tables[source] = read_tsv(path, name=f"{split}/{path.name}")
    return RawDataset(split=split, **tables)


def stream_split(split: str = "train", root: str | Path | None = None) -> dict[str, Path]:
    """Return the three file paths of a split without reading anything."""
    return {source: source_path(split, source, root) for source in SOURCES}


def load_train(train_dir: str | Path | None = None) -> RawDataset:
    """Load the training split."""
    return load_split(train_dir, "train")


def load_test(test_dir: str | Path | None = None) -> RawDataset:
    """Load the test split."""
    return load_split(test_dir, "test")


