"""Loading the TSV challenge files.

Every file is read with ``pd.read_csv(path, sep="\\t")`` as required by the
challenge specification.  IDs are read as strings so identifiers such as
``"007"`` survive round-tripping, and no assumption is made about the number of
rows in any file.

Dataset location
----------------
The repository ships the real Amazon ML Challenge files **and** a small synthetic
fixture used by the test suite.  They are not interchangeable -- the fixture has
1,500 Source 1 rows and 0.4 MB in total, the real data has 2,206,821 Source 1
rows and 2.7 GB.  :func:`resolve_dataset_root` auto-detects which one is present
and always prefers the real data, so a stale ``dataset/train`` path can never
silently train a model on the fixture.

Memory
------
The real data does not fit in RAM on a typical machine (Source 2 alone is
5,034,616 rows / 467 MB of text).  Use :func:`read_tsv_chunks` or
:meth:`RawDataset.iter_chunks` for anything that scans a whole file;
:func:`read_tsv` is kept for small tables and the test fixture.
"""

